/**
 * CADClone — Native Autodesk DWG / DXF WebAssembly Engine
 * Powered by pure Rust acadrust compiled to WebAssembly.
 * Enables 100% client-side, offline, high-speed DWG read and write.
 */
const CadDwg = {
    ready: false,
    loadingPromise: null,
    wasmModule: null,

    /**
     * Initializes the WebAssembly engine in the browser.
     * Safe to call multiple times (cached).
     */
    async init() {
        if (this.ready) return true;
        if (this.loadingPromise) return this.loadingPromise;

        this.loadingPromise = (async () => {
            try {
                // Dynamically import the ES module wrapper generated by wasm-bindgen
                const wasm = await import('./dwg/cadclone_dwg.js');
                // Initialize WASM binary
                await wasm.default({ module_or_path: './dwg/cadclone_dwg_bg.wasm' });
                
                if (typeof wasm.is_dwg_ready === 'function' && wasm.is_dwg_ready()) {
                    this.wasmModule = wasm;
                    this.ready = true;
                    console.log('⚡ [CADClone] Motor Nativo WebAssembly DWG/DXF carregado com sucesso!');
                    return true;
                }
                throw new Error('Falha na validação do módulo WASM DWG.');
            } catch (err) {
                console.warn('⚠️ [CADClone] Não foi possível inicializar o motor DWG WASM:', err);
                this.ready = false;
                return false;
            }
        })();

        return this.loadingPromise;
    },

    /**
     * Converts a binary DWG buffer (ArrayBuffer or Uint8Array) into standard DXF text.
     * @param {ArrayBuffer|Uint8Array} input
     * @returns {Promise<string>} DXF text content
     */
    async convertDwgToDxf(input) {
        await this.init();
        if (!this.ready || !this.wasmModule) {
            throw new Error('Motor DWG WebAssembly não disponível.');
        }

        const uint8 = (input instanceof Uint8Array) ? input : new Uint8Array(input);
        if (uint8.length === 0) {
            throw new Error('Arquivo DWG vazio.');
        }

        return this.wasmModule.dwg_to_dxf(uint8);
    },

    /**
     * Converts standard DXF text into a native Autodesk DWG binary Uint8Array.
     * @param {string} dxfString
     * @param {string} version - Target DWG version: '2018', '2013', '2010', '2007', '2004', '2000', 'R14'
     * @returns {Promise<Uint8Array>} DWG binary bytes
     */
    async convertDxfToDwg(dxfString, version = '2018') {
        await this.init();
        if (!this.ready || !this.wasmModule) {
            throw new Error('Motor DWG WebAssembly não disponível.');
        }

        if (!dxfString || !dxfString.trim()) {
            throw new Error('Conteúdo do desenho DXF está vazio.');
        }

        const dwgBytes = this.wasmModule.dxf_to_dwg(dxfString, version);
        if (!dwgBytes || dwgBytes.length === 0) {
            throw new Error('Erro ao gerar binário DWG.');
        }

        return dwgBytes;
    }
};

// Auto-start WASM loading in background for instant availability
if (typeof window !== 'undefined') {
    window.CadDwg = CadDwg;
    window.addEventListener('DOMContentLoaded', () => {
        CadDwg.init().catch(() => {});
    });
}
